import { test, expect } from "@playwright/test";
import { stl } from "../fixtures.js";
test("Cloudflare student upload, teacher console and View at home use private R2 files", async ({ page, request }) => {
  const errors = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("http://127.0.0.1:4174/");
  await expect(page.getByRole("heading", { name: "UPLOAD YOUR 3D PRINTING FILES" })).toBeVisible();
  await expect(page.getByText("Up to 50 MB per file")).toBeVisible();
  const home = page.getByRole("region", { name: "View at home" });
  await expect(home).toBeVisible();
  await page
    .getByLabel("Upload a 3D printing file")
    .setInputFiles({ name: "home-model.stl", mimeType: "model/stl", buffer: stl() });
  await expect(page.getByText("No common issues found")).toBeVisible();
  await page.getByText("I’ve checked my model and it’s ready for the printing team.").click();
  await page.getByRole("button", { name: "Confirm my model" }).click();
  await page.getByLabel("First name").fill("Ava");
  await page.getByLabel("School", { exact: false }).first().selectOption({ label: "School A" });
  await page.getByLabel("BNTS staff member").selectOption({ label: "Alex" });
  await page.getByLabel("Additional notes").fill("Private print instructions for staff.");
  await page.getByRole("button", { name: "Review my request" }).click();
  await page.getByText("Everything looks right. Send my file to the printing team.").click();
  await page.getByRole("button", { name: "Submit for printing" }).click();
  await expect(page.getByRole("heading", { name: "File submitted." })).toBeVisible();
  await home.getByLabel("School").selectOption({ label: "School A" });
  await home.getByLabel("First name").fill("Ava");
  const lookupResponse = page.waitForResponse((r) => r.url().endsWith("/api/student/lookup"));
  await home.getByRole("button", { name: "View files" }).click();
  const lookup = await (await lookupResponse).json();
  expect(lookup.files).toHaveLength(1);
  expect(JSON.stringify(lookup)).not.toContain("Private print instructions");
  await home.getByRole("button", { name: /home-model.stl/ }).click();
  await expect(page.getByRole("dialog")).toBeVisible();
  await expect(page.getByRole("dialog").locator("canvas")).toBeVisible();
  await page.getByRole("button", { name: "Close model" }).click();
  await page.screenshot({ path: "test-results/cloudflare-view-at-home.png", fullPage: true });
  await page.goto("http://127.0.0.1:4174/teacher");
  await page.getByLabel("Teacher password").fill("local-demo-teacher-password");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await page.getByRole("button", { name: "Setup & supplies" }).click();
  await expect(
    page.getByText("Files are stored privately on Cloudflare. No Google connection is needed."),
  ).toBeVisible();
  await expect(page.getByLabel("Shared Google Drive folder link")).toHaveCount(0);
  await expect(page.getByText("8 GB limit", { exact: false })).toBeVisible();
  await page.getByRole("button", { name: "Save setup" }).click();
  await expect(page.getByText("Setup saved. Your student upload page uses these options.")).toBeVisible();
  await page.getByRole("button", { name: "Print queue" }).click();
  await page.getByRole("button", { name: /School A.*Open school/ }).click();
  await page.getByRole("button", { name: /View designs/ }).click();
  await page.getByRole("button", { name: /Ava.*home-model.stl/ }).click();
  await expect(page.getByText("Private print instructions for staff.")).toBeVisible();
  const download = page.waitForEvent("download");
  await page.getByRole("link", { name: "Download original STL" }).click();
  expect((await download).suggestedFilename()).toMatch(/^School-A_/);
  await page.getByRole("button", { name: "Close preview" }).click();
  await request.post(`http://127.0.0.1:4173/__cf-test/expire/${lookup.files[0].id}`);
  await page.goto("http://127.0.0.1:4174/");
  const again = page.getByRole("region", { name: "View at home" });
  await again.getByLabel("School").selectOption({ label: "School A" });
  await again.getByLabel("First name").fill("Ava");
  await again.getByRole("button", { name: "View files" }).click();
  await expect(again.getByText("This has been deleted.")).toBeVisible();
  expect(errors).toEqual([]);
});
test("Cloudflare View at home fits a mobile screen and displays missing files", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("http://127.0.0.1:4174/");
  const home = page.getByRole("region", { name: "View at home" });
  await home.getByLabel("School").selectOption({ label: "School A" });
  await home.getByLabel("First name").fill("NoMatchingStudent");
  await home.getByRole("button", { name: "View files" }).click();
  await expect(home.getByText("This has been deleted.")).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.screenshot({ path: "test-results/cloudflare-mobile.png", fullPage: true });
});

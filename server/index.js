import 'dotenv/config';
import path from 'node:path';
import { createApp } from './app.js';
import { LocalStore, DriveStore } from './storage.js';
const production = process.env.NODE_ENV === 'production';
const local = process.env.STORAGE_MODE === 'local';
const password = process.env.TEACHER_PASSWORD;
const secret = process.env.SESSION_SECRET;
if (!password || password.length < 12 || !secret || secret.length < 32) throw new Error('Set TEACHER_PASSWORD (12+ characters) and SESSION_SECRET (32+ random characters). See .env.example.');
if (production && local) throw new Error('Local storage is development-only. Use Google Drive in production; Render free disks are ephemeral.');
const store = local ? new LocalStore(path.resolve(process.env.LOCAL_DATA_DIR || '.local-data')) : new DriveStore();
await store.init();
const { app, cleanup } = createApp({ store, password, secret, production, cleanupSecret: process.env.CLEANUP_SECRET });
const port = Number(process.env.PORT || 3000);
const server = app.listen(port, '0.0.0.0', () => console.log(`BNTS Print Studio listening on port ${port}${local ? ' · LOCAL DEMO STORAGE' : ''}`));
server.requestTimeout = 10 * 60 * 1000;
const runCleanup = () => cleanup().then(r => console.log('Retention cleanup complete:', r.deletedSubmissions, 'submissions removed')).catch(() => console.error('Retention cleanup failed. Check the Drive connection in the teacher console.'));
runCleanup();
const timer = setInterval(runCleanup, 60 * 60 * 1000); timer.unref();
process.on('SIGTERM', () => { clearInterval(timer); server.close(); });
